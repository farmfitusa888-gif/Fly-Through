"""Generate the vehicle and product shot guides from their own taxonomies.

    python3 docs/shot_guide_ads.py

Writes into docs/:
    shot-guide-vehicle.md    for a dealer's lot photographer
    shot-guide-product.md    for a brand sending product stills

Same reason docs/shot_guide.py is generated rather than written: the rules live
in vehicles.TOUR_ORDER / REQUIRED_ANCHORS / NON_HERO and products.*, and a
hand-written guide drifts from the validator the first time either changes. The
drift surfaces as a customer who followed the instructions and still got a
warning, which is the worst possible place to discover it.

Deliberately NOT merged with the property guide. Its copy is built around a
buyer walking a house and an aerial rule that has no analogue here; a dealer
needs to hear about proof shots and trim options instead. A shared template
would produce two worse guides, so what is shared is the taxonomy, not the prose.
"""

