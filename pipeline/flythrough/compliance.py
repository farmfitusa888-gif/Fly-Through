def make_page(
    listing: str,
    photos: list[dict],
    out: str | Path,
    *,
    url: str,
    produced_by: str = "FlyThrough",
) -> Path:
    """Build the hosted originals page.

    This is the artefact AB 723 asks for: the unaltered images, reachable from
    the advertisement by URL or QR. Photos are referenced by filename, so the
    page ships next to a folder of the agent's own originals -- it never embeds a
    re-encoded copy, because a re-encode is itself an alteration.
    """
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)

    cards = "\n".join(
        f'      <figure><img src="originals/{html.escape(Path(p["path"]).name)}" '
        f'alt="{html.escape(p["room_key"].replace("_", " "))}" loading="lazy">'
        f'<figcaption>{html.escape(p["room_key"].replace("_", " "))}</figcaption></figure>'
        for p in photos
    )

    doc = f"""<title>Original Photos — {html.escape(listing)}</title>
<style>{PAGE_CSS}</style>
<div class="wrap">
  <h1>Original, unaltered photographs</h1>
  <p class="addr">{html.escape(listing)}</p>

  <div class="notice">
    <h2>About the video</h2>
    <p>The listing video for this property is an <strong>AI-generated video</strong>.
       The camera movement was created from the still photographs on this page.
       It is not drone footage and it is not a walkthrough recording.</p>
    <p>Every photograph below is the original file supplied by the listing agent,
       unaltered. Nothing on this page has been staged, retouched or generated.</p>
  </div>

  <div class="grid">
{cards}
  </div>

  <footer>
    Published to satisfy disclosure of digitally altered imagery, including
    California Business &amp; Professions Code &sect;10140.8 and NAR Code of Ethics
    Article 12. Page URL: {html.escape(url)} &middot; Produced by {html.escape(produced_by)}.
  </footer>
</div>
"""
    out.write_text(doc)
    return out


def build_pack(
    listing: str,
    photos: list[dict],
    outdir: str | Path,
    *,
    url: str,
    slug: str,
) -> DisclosurePack:
    """Produce every disclosure artefact for one job."""
    outdir = Path(outdir)
    card = make_card(url, outdir / f"{slug}_disclosure_card.mp4")
    qr = make_qr(url, outdir / f"{slug}_originals_qr.png")
    page = make_page(listing, photos, outdir / "originals.html", url=url)

    pack = DisclosurePack(
        card=card, page=page, qr=qr, url=url,
        caption=CAPTION.format(url=url),
        caption_short=CAPTION_SHORT.format(url=url),
    )
    (outdir / f"{slug}_disclosure.json").write_text(json.dumps({
        "listing": listing,
        "url": url,
        "caption_mls": pack.caption,
        "caption_social": pack.caption_short,
        "card": str(card),
        "qr": str(qr),
        "page": str(page),
        "basis": [
            "NAR Code of Ethics Article 12 / Standard of Practice 12-5",
            "California Business & Professions Code 10140.8 (AB 723), effective 2026-01-01",
        ],
        "not_legal_advice": True,
    }, indent=2))
    return pack
